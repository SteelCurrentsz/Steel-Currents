// Turns the Natural Earth 1:50m land topology into a data module the client
// can ship. TopoJSON is already delta-encoded against a quantisation grid, so
// it travels far smaller than the equivalent list of coordinates — the client
// carries a short decoder instead.
//
//   node build/genworld.mjs   ->  client/js/worlddata.js

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = path.join(ROOT, 'node_modules/world-atlas/land-50m.json');
const topo = JSON.parse(fs.readFileSync(src, 'utf8'));

// The land object is a collection holding a single MultiPolygon.
const geoms = topo.objects.land.geometries.filter((g) => g.type === 'MultiPolygon');
if (!geoms.length) throw new Error('no MultiPolygon in the land object');
const polygons = geoms.flatMap((g) => g.arcs);

const out = {
  transform: topo.transform,
  arcs: topo.arcs,
  polygons,
};

const body = `// GENERATED by build/genworld.mjs — do not edit by hand.
//
// Natural Earth 1:50m land, as TopoJSON: a quantisation transform, the shared
// arcs in delta-encoded grid units, and the polygon rings that index them.
// Public domain (naturalearthdata.com), repackaged by the world-atlas project.

export const LAND_TOPOLOGY = ${JSON.stringify(out)};
`;

const dest = path.join(ROOT, 'client/js/worlddata.js');
fs.writeFileSync(dest, body);
console.log(`client/js/worlddata.js — ${Math.round(body.length / 1024)} KB, ` +
  `${out.arcs.length} arcs, ${out.polygons.length} polygons`);
