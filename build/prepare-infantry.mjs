// Turn the owner's models of an American soldier and of his rifle into what
// client/js/render/infantry.js draws: the man cut at his joints into the
// pieces a walk, a run, a crouch and a rifle brought up to the shoulder are
// made of, each painted the colour of the model's own paint under it and cut
// down to what a battlefield with hundreds of men on it can afford -- twice,
// once for close to and once for far off -- and the rifle the same.
//
//   npm i --no-save meshoptimizer@0.22 sharp     (see build/sculpt-source.mjs)
//   SCULPT_TOOLS=<that node_modules> node build/prepare-infantry.mjs
//
// Reads, as the owner uploaded them:
//   assets/models/american_soldier_ww2.glb -- "American Soldier WW2"
//     (https://skfb.ly/pI7S8) by Diplomattheftgun1945, under Creative Commons
//     Attribution 4.0;
//   assets/models/m1_garand_asset-maximum-compressed.glb -- "M1 Garand Asset"
//     (https://skfb.ly/oPwXw) by lennur, under Creative Commons Attribution 4.0.
// Both credited on the game's Credits screen.
//
// Writes client/js/render/infantry.data.js, which is committed, so a fresh
// clone runs without this script.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { flatten, bounds, part, pack } from './glbkit.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'client/js/render/infantry.data.js');

const out = [
  '// Generated by build/prepare-infantry.mjs from the owner\'s models.',
  '// Do not hand-edit -- regenerate from the source assets instead.',
];

const mean = (pts) => {
  const s = [0, 0, 0];
  for (const p of pts) for (let c = 0; c < 3; c++) s[c] += p[c];
  return s.map((v) => v / Math.max(1, pts.length));
};

// ---- the soldier -------------------------------------------------------------------
{
  const m = await flatten(path.join(ROOT, 'assets/models/american_soldier_ww2.glb'));
  const all = Array.from({ length: m.T.length / 3 }, (_, i) => i);
  const { lo, hi } = bounds(m.P, m.T);
  console.log('soldier:', all.length, 'faces; box', lo.map((v) => v.toFixed(2)), hi.map((v) => v.toFixed(2)));
  // He stands with his feet on the bottom of the box, facing +Z, and is a
  // man of five foot ten.
  const S = 1.78 / (hi[1] - lo[1]);
  const at = (v) => [m.P[v * 3] * S, (m.P[v * 3 + 1] - lo[1]) * S, m.P[v * 3 + 2] * S];
  const mid = (t) => mean([0, 1, 2].map((k) => at(m.T[t * 3 + k])));
  const H = 1.78;
  // Where he is cut, by the middle of each face: the head and helmet over the
  // collar; the arms out past the shoulder seam (and clear of the pouches on
  // his belt); the legs under the belt; and each limb again at the elbow and
  // the knee.
  const NECK = H * 0.815, SHOULDER = 0.215 * S, ELBOW = 0.415 * S, HIP = H * 0.5, KNEE = H * 0.255;
  const pieceOf = (t) => {
    const [x, y] = mid(t);
    const ax = Math.abs(x);
    // Facing +Z with +Y up, his right hand is out on -X.
    const side = x < 0 ? 'R' : 'L';
    if (y > NECK && ax < 0.15) return 'head';
    if ((ax > SHOULDER && y > H * 0.66) || ax > 0.3 * S) return (ax > ELBOW ? 'farm' : 'uarm') + side;
    if (y < HIP - 0.02) return (y < KNEE ? 'shin' : 'thigh') + side;
    return 'torso';
  };
  const groups = {};
  for (const t of all) (groups[pieceOf(t)] ||= []).push(t);
  for (const [k, v] of Object.entries(groups)) console.log(' ', k, v.length);
  const vertsOf = (ts) => ts.flatMap((t) => [0, 1, 2].map((k) => at(m.T[t * 3 + k])));
  // The joints, off the cut faces themselves.
  const joint = (ts, test) => mean(vertsOf(ts).filter(test));
  const J = {};
  for (const sd of ['L', 'R']) {
    const sg = sd === 'R' ? -1 : 1;
    J[`shoulder${sd}`] = joint(groups[`uarm${sd}`], (p) => Math.abs(p[0]) < SHOULDER + 0.04);
    J[`elbow${sd}`] = joint([...groups[`uarm${sd}`], ...groups[`farm${sd}`]], (p) => Math.abs(Math.abs(p[0]) - ELBOW) < 0.025);
    // The hand: the far end of the forearm, where the grip goes.
    const fv = vertsOf(groups[`farm${sd}`]);
    const far = Math.max(...fv.map((p) => Math.abs(p[0])));
    J[`hand${sd}`] = mean(fv.filter((p) => Math.abs(p[0]) > far - 0.09));
    J[`hip${sd}`] = [sg * 0.095, HIP, joint(groups[`thigh${sd}`], (p) => Math.abs(p[1] - HIP) < 0.05)[2]];
    J[`knee${sd}`] = joint([...groups[`thigh${sd}`], ...groups[`shin${sd}`]], (p) => Math.abs(p[1] - KNEE) < 0.03);
    J[`ankle${sd}`] = joint(groups[`shin${sd}`], (p) => Math.abs(p[1] - 0.1) < 0.03);
  }
  J.neck = [0, NECK, joint(groups.head, (p) => Math.abs(p[1] - NECK) < 0.03)[2]];
  J.waist = [0, HIP, (J.hipL[2] + J.hipR[2]) / 2];
  for (const [k, v] of Object.entries(J)) console.log('  joint', k, v.map((n) => n.toFixed(3)).join(', '));
  const pivotOf = {
    head: J.neck, torso: J.waist,
    uarmL: J.shoulderL, uarmR: J.shoulderR, farmL: J.elbowL, farmR: J.elbowR,
    thighL: J.hipL, thighR: J.hipR, shinL: J.kneeL, shinR: J.kneeR,
  };
  // Faces' budgets, close to and far off.
  const NEAR = { head: 520, torso: 700, uarm: 140, farm: 220, thigh: 160, shin: 200 };
  const FAR = { head: 60, torso: 90, uarm: 18, farm: 24, thigh: 22, shin: 28 };
  const lines = [];
  for (const lod of [['NEAR', NEAR], ['FAR', FAR]]) {
    const parts = [];
    for (const [k, ts] of Object.entries(groups)) {
      const base = k.replace(/[LR]$/, '');
      const pv = pivotOf[k];
      console.log(`  ${lod[0]} ${k}`);
      const p = part(m, ts, lod[1][base], (x, y, z) => {
        const q = [x * S, (y - lo[1]) * S, z * S];
        return [q[0] - pv[0], q[1] - pv[1], q[2] - pv[2]];
      });
      parts.push(`${k}: "${pack(p)}"`);
    }
    lines.push(`export const SOLDIER_${lod[0]} = {\n  ${parts.join(',\n  ')},\n};`);
  }
  out.push(...lines);
  const r3 = (v) => v.map((n) => +n.toFixed(3));
  out.push(`export const SOLDIER_JOINTS = {\n${Object.entries(J).map(([k, v]) => `  ${k}: [${r3(v).join(', ')}],`).join('\n')}\n};`);
  out.push(`export const SOLDIER_PIVOTS = {\n${Object.entries(pivotOf).map(([k, v]) => `  ${k}: [${r3(v).join(', ')}],`).join('\n')}\n};`);
}

// ---- the rifle ---------------------------------------------------------------------
{
  const m = await flatten(path.join(ROOT, 'assets/models/m1_garand_asset-maximum-compressed.glb'));
  const all = Array.from({ length: m.T.length / 3 }, (_, i) => i);
  const { lo, hi } = bounds(m.P, m.T);
  const ext = [0, 1, 2].map((c) => hi[c] - lo[c]);
  const along = ext[0] > ext[2] ? 0 : 2;
  // The muzzle is the slim end: the less of the model there is in the last
  // tenth of its length at that end, the more it is the barrel.
  let a0 = 0, a1 = 0;
  for (let v = 0; v < m.P.length / 3; v++) {
    const a = (m.P[v * 3 + along] - lo[along]) / ext[along];
    const h = m.P[v * 3 + 1];
    if (a < 0.1) a0 = Math.max(a0, Math.abs(h)); else if (a > 0.9) a1 = Math.max(a1, Math.abs(h));
  }
  const muzzleHigh = a1 < a0;
  // 43.6 inches overall.
  const S = 1.107 / ext[along];
  const across = along === 0 ? 2 : 0;
  const yMid = (lo[1] + hi[1]) / 2;
  console.log('rifle:', all.length, 'faces; muzzle at the', muzzleHigh ? 'high' : 'low', 'end; scale', S.toFixed(5));
  // Butt plate at the origin, muzzle up +Z, sights up +Y.
  const xf = (x, y, z) => {
    const p = [x, y, z];
    const t = muzzleHigh ? p[along] - lo[along] : hi[along] - p[along];
    const side = (p[across] - (lo[across] + hi[across]) / 2) * (muzzleHigh ? 1 : -1) * (along === 0 ? -1 : 1);
    return [side * S, (p[1] - yMid) * S, t * S];
  };
  out.push(`export const GARAND_NEAR = "${pack(part(m, all, 700, xf))}";`);
  out.push(`export const GARAND_FAR = "${pack(part(m, all, 70, xf))}";`);
  out.push('export const GARAND_LENGTH = 1.107;');
}

writeFileSync(OUT, out.join('\n') + '\n');
console.log('wrote', path.relative(ROOT, OUT));
