// Turn the machinery and fittings made with Meshy for the inside of a warship
// (assets/models/meshy-interior/) into what client/js/render/interior.js
// draws in place of its own box-built ones: the boilers, the geared turbines,
// the turbo-generators, the shell racks of the magazines, the steering gear
// in the tiller flat and the crew's bunks on the mess decks.
//
//   npm i --no-save meshoptimizer@0.22 sharp     (see build/sculpt-source.mjs)
//   SCULPT_TOOLS=<that node_modules> node build/prepare-interior.mjs
//
// Each is painted at every corner off the model's own texture -- an inside is
// welded into one buffer with the rest of her, so it carries no texture of its
// own -- and cut down to what a battleship with eight boilers, two dozen
// racks and her mess decks can afford: every ship carries her insides
// whether or not anything has opened her up yet. Each is turned so that its
// long axis is the one the interior lays it along (see MODELS), centred on x and z, standing on y = 0,
// and scaled so that its largest side is one: interior.js fits it into the
// room the ship has for it.
//
// Writes client/js/render/interiorModels.data.js, which is committed, so a
// fresh clone runs without this script.
import { existsSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { flatten, bounds, part, pack } from './glbkit.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'assets/models/meshy-interior');
const OUT = path.join(ROOT, 'client/js/render/interiorModels.data.js');

// `turn`: quarter turns about the vertical, (x, z) -> (z, -x) each.
// `faces`: what it is cut to. `tint`: multiplied into its paint, where Meshy
// painted it all one grey.
const MODELS = {
  // A drum lying athwartships: its length along x, its furnace front to +z.
  boiler: { turn: 0, faces: 900 },
  // A turbine set: its length fore and aft, along z.
  turbine: { turn: 1, faces: 1100 },
  // A turbo-generator on its bedplate, along z.
  generator: { turn: 1, faces: 800 },
  // A rack of shells stood on end: the row along z, facing +x. Meshy painted
  // shell and rack the same dull grey; a magazine is brass and red lead.
  shells: { turn: 1, faces: 450, tint: [1.25, 1.08, 0.72] },
  // The steering gear: the quadrant athwartships, along x.
  steering: { turn: 0, faces: 800 },
  // Two tiers of bunks and the lockers between: the row along z, facing +x.
  bunks: { turn: 1, faces: 700 },
};
for (const [k, v] of Object.entries(MODELS)) {
  const e = process.env[`TURN_${k.toUpperCase()}`];
  if (e !== undefined) v.turn = +e;
}

const out = [
  '// Generated by build/prepare-interior.mjs from the Meshy interior models.',
  '// Do not hand-edit -- regenerate from assets/models/meshy-interior/ instead.',
];
const entries = [];
for (const [name, cfg] of Object.entries(MODELS)) {
  const file = path.join(SRC, `${name}.glb`);
  if (!existsSync(file)) { console.log(`${name}: no model yet`); continue; }
  const m = await flatten(file);
  if (cfg.tint) {
    for (let i = 0; i < m.TC.length; i++) m.TC[i] = Math.min(1, m.TC[i] * cfg.tint[i % 3]);
  }
  const all = Array.from({ length: m.T.length / 3 }, (_, i) => i);
  const { lo, hi } = bounds(m.P, m.T);
  const cx = (lo[0] + hi[0]) / 2, cz = (lo[2] + hi[2]) / 2;
  const turn = (x, z) => {
    for (let k = 0; k < ((cfg.turn % 4) + 4) % 4; k++) [x, z] = [z, -x];
    return [x, z];
  };
  const one = 1 / Math.max(hi[0] - lo[0], hi[1] - lo[1], hi[2] - lo[2]);
  const xf = (x, y, z) => {
    const [a, c] = turn(x - cx, z - cz);
    return [a * one, (y - lo[1]) * one, c * one];
  };
  const p = part(m, all, cfg.faces, xf);
  const b = bounds(p.P, Array.from({ length: p.P.length / 3 }, (_, i) => i));
  console.log(`${name}: ${m.T.length / 3} faces in; ${b.hi.map((h, i) => (h - b.lo[i]).toFixed(2)).join(' x ')}`);
  entries.push(`  ${name}: "${pack(p)}",`);
}
out.push('export const INTERIOR_MODELS = {', ...entries, '};', '');
writeFileSync(OUT, out.join('\n'));
console.log(`wrote ${path.relative(ROOT, OUT)}`);
